// تحقق خفيف من حقول تسجيل الدخول في الواجهة فقط (الخادم هو المرجع الفعلي لاحقاً).
// كل دالة تعيد رسالة الخطأ بالعربية، أو '' إن كانت القيمة صحيحة.

// بريد معقول وغير مبالغ في تشدده: جزء محلي، ثم @، ثم نطاق من مقطعين على الأقل بلا نقاط متتالية، ولا فراغات.
const EMAIL_PATTERN = /^[^\s@]+@[^\s@.]+(\.[^\s@.]+)+$/;

export function validateEmail(value) {
  const email = String(value ?? '').trim();
  if (!email) return 'أدخل البريد الإلكتروني.';
  if (!EMAIL_PATTERN.test(email)) return 'أدخل بريداً إلكترونياً صحيحاً.';
  return '';
}

// لا قواعد تعقيد هنا (هي لشاشة التسجيل لاحقاً): يُرفض الفارغ فقط، ولا تُقصّ كلمة المرور.
export function validatePassword(value) {
  if (!value) return 'أدخل كلمة المرور.';
  return '';
}
